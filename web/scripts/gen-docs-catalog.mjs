import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const sources = {
  "contracts/core": ["src/interfaces/ICore.sol"],
  "contracts/controller": ["src/interfaces/IControllerV1.sol"],
  "contracts/balance-module": ["src/interfaces/IStatementBalanceModule.sol"],
  "contracts/adapters": [
    "src/interfaces/IListingAdapter.sol",
    "src/interfaces/ISeaportBasicAdapter.sol",
    "src/interfaces/ICreditStrategyAdapter.sol",
  ],
};

const catalog = Object.fromEntries(Object.entries(sources).map(([slug, files]) => [
  slug,
  files.map((file) => {
    const contents = readFileSync(new URL(`../../${file}`, import.meta.url), "utf8")
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/\/\/[^\n]*/g, "");
    const declarations = [...contents.matchAll(/\b(function|event|error)\s+[A-Za-z_]\w*\s*\([\s\S]*?;/g)]
      .map((match) => ({ kind: match[1], signature: match[0].replace(/\s+/g, " ").trim().replace(/;$/, "") }));
    const receive = contents.match(/\breceive\s*\(\s*\)\s*external\s*payable\s*;/);
    if (receive) declarations.push({ kind: "function", signature: receive[0].replace(/\s+/g, " ").replace(/;$/, "") });
    assert(declarations.some((entry) => entry.kind === "function"), `${file} has no functions`);
    return { file, declarations };
  }),
]));

const output = `// Generated by web/scripts/gen-docs-catalog.mjs from src/interfaces. Do not edit by hand.\nexport const contractCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`;
const destination = new URL("../lib/docs-catalog.ts", import.meta.url);
if (process.argv.includes("--check")) {
  assert.equal(readFileSync(destination, "utf8"), output, "docs catalog is stale; run npm run gen:docs");
  console.log("docs catalog matches generated interfaces");
} else {
  writeFileSync(destination, output);
  console.log("docs catalog generated from interfaces");
}
