// Usage: node scripts/local-env.mjs <deployments/31337.json> [rpcUrl]
// Writes web/.env.local for the local anvil fork from a deployment record.
// Record format: see CONNECTIONS.md "local anvil".
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [recordPath, rpc = "http://127.0.0.1:8545"] = process.argv.slice(2);
if (!recordPath) {
  console.error("usage: node scripts/local-env.mjs <deployments/31337.json> [rpcUrl]");
  process.exit(1);
}

const rec = JSON.parse(readFileSync(recordPath, "utf8"));
if (rec.chainId !== 31337) throw new Error(`record chainId ${rec.chainId}, expected 31337`);

const isAddr = (v) => typeof v === "string" && /^0x[0-9a-fA-F]{40}$/.test(v);
const need = (k) => {
  if (!isAddr(rec[k])) throw new Error(`record.${k} is not an address: ${rec[k]}`);
  return rec[k];
};
if (!Number.isInteger(rec.block) || rec.block < 0) throw new Error(`record.block invalid: ${rec.block}`);

const env = {
  NEXT_PUBLIC_CHAIN_ID: "31337",
  NEXT_PUBLIC_RPC_URL: rpc,
  NEXT_PUBLIC_CORE: need("core"),
  NEXT_PUBLIC_CORE_LENS: need("lens"),
  NEXT_PUBLIC_CREDITS: need("credits"),
  NEXT_PUBLIC_CC: need("coin"),
  NEXT_PUBLIC_ROUTER: need("router"),
  NEXT_PUBLIC_DEPLOY_BLOCK: String(rec.block),
};
// Optional: skim hook of the deployed pool (the app builds the pool key from it).
if (rec.hook != null) env.NEXT_PUBLIC_POOL_HOOK = need("hook");
// Optional: the account the app's local wallet acts as. From the environment,
// else record.localAccount, else the app default
// (0x1111111111111111111111111111111111111111).
const acct = process.env.NEXT_PUBLIC_LOCAL_ACCOUNT ?? rec.localAccount;
if (acct != null) {
  if (!isAddr(acct)) throw new Error(`local account is not an address: ${acct}`);
  env.NEXT_PUBLIC_LOCAL_ACCOUNT = acct;
}

const out = fileURLToPath(new URL("../.env.local", import.meta.url));
writeFileSync(
  out,
  "# generated by scripts/local-env.mjs; public local anvil addresses only\n" +
    Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") + "\n"
);
console.log(`wrote ${out}`);
