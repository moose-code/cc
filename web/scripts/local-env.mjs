// Usage: node scripts/local-env.mjs [deployments/31337.json] [rpcUrl]
// Writes web/.env.local for the local anvil from a deployment record, or
// prints why it cannot and exits 1.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [recordPath = "../deployments/31337.json", rpc = "http://127.0.0.1:8545"] = process.argv.slice(2);
const fail = (m) => {
  console.error(`dev:local: ${m}`);
  process.exit(1);
};

if (!existsSync(recordPath))
  fail(
    `deployment record not found: ${recordPath}\n` +
      "start anvil with --auto-impersonate and run the local deploy script, which writes deployments/31337.json.\n" +
      "RECORD=<path> npm run dev:local reads another file."
  );

let rec;
try {
  rec = JSON.parse(readFileSync(recordPath, "utf8"));
} catch (e) {
  fail(`${recordPath} is not valid json: ${e.message}`);
}
if (rec.chainId !== 31337) fail(`record chainId ${rec.chainId}, expected 31337`);

const isAddr = (v) => typeof v === "string" && /^0x[0-9a-fA-F]{40}$/.test(v);
if (!isAddr(rec.core)) fail(`record.core is not an address: ${rec.core}`);
if (!Number.isInteger(rec.deployBlock) || rec.deployBlock < 0) fail(`record.deployBlock invalid: ${rec.deployBlock}`);
if (!isAddr(rec.hook)) fail(`record.hook is not an address: ${rec.hook}`);
if (!Number.isInteger(rec.poolFee) || !Number.isInteger(rec.tickSpacing)) fail("record.poolFee or record.tickSpacing missing");
const accounts = Object.fromEntries(Object.entries(rec.accounts ?? {}).filter(([, a]) => isAddr(a)));
if (Object.keys(accounts).length === 0) fail("record.accounts has no address");

const env = {
  NEXT_PUBLIC_CHAIN_ID: "31337",
  NEXT_PUBLIC_RPC_URL: rec.rpcUrl ?? rpc,
  NEXT_PUBLIC_CORE: rec.core,
  NEXT_PUBLIC_DEPLOY_BLOCK: String(rec.deployBlock),
  NEXT_PUBLIC_POOL_HOOK: rec.hook,
  NEXT_PUBLIC_POOL_FEE: String(rec.poolFee),
  NEXT_PUBLIC_POOL_TICK_SPACING: String(rec.tickSpacing),
  NEXT_PUBLIC_LOCAL_ACCOUNTS: JSON.stringify(accounts),
  NEXT_PUBLIC_INDEXER_URL: process.env.NEXT_PUBLIC_INDEXER_URL ?? "http://localhost:42169",
};

const out = fileURLToPath(new URL("../.env.local", import.meta.url));
writeFileSync(out, "# generated by scripts/local-env.mjs; public local anvil addresses only\n" + Object.entries(env).map(([k, v]) => `${k}=${k === "NEXT_PUBLIC_LOCAL_ACCOUNTS" ? `'${v}'` : v}`).join("\n") + "\n");
console.log(`wrote ${out}`);
