// Generates abis/Core.ts and abis/ControllerV1.ts from forge artifacts.
// Core: Core functions and events plus the CoreLib and CoreOpsLib events, emitted under the Core address
// through delegatecall, so the union is the Core's log ABI.
// Usage: node scripts/gen-abis.mjs [outDir]   (default ../out, run `forge build` first)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(process.argv[2] ?? join(here, "../../out"));
const abiOf = (name) => JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8")).abi;

const sig = (e) => `${e.type}:${e.name}(${(e.inputs ?? []).map((i) => i.type + (i.indexed ? "!" : "")).join(",")})`;

const core = abiOf("Core");
const lib = abiOf("CoreLib");
const seen = new Set(core.filter((e) => e.type === "event").map(sig));
const merged = [...core, ...lib.filter((e) => e.type === "event" && !seen.has(sig(e)))];

const emit = (file, constName, abi, note) =>
  writeFileSync(
    join(here, "../abis", file),
    `// Generated by scripts/gen-abis.mjs from forge artifacts. Do not edit.\n// ${note}\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );

emit("Core.ts", "coreAbi", merged, "Core ABI plus CoreLib events.");
emit("ControllerV1.ts", "controllerAbi", abiOf("ControllerV1"), "ControllerV1 ABI.");
console.log(`Core: ${merged.length} entries (${merged.filter((e) => e.type === "event").length} events); ControllerV1 written`);
